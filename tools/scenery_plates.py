"""Raster Fair scenery plates, drawn on a 128 x 88 two-pixel design grid."""
from math import cos, sin, tau, sqrt, ceil


class Plate:
    def __init__(self):
        self.rows = [bytearray(128) for _ in range(88)]

    def dot(self,x,y,c):
        x,y=round(x),round(y)
        if 0<=x<128 and 0<=y<88: self.rows[y][x]=c

    def line(self,c,*points):
        for (x,y),(u,v) in zip(points,points[1:]):
            n=max(1,abs(u-x),abs(v-y))
            for k in range(n+1): self.dot(x+(u-x)*k/n,y+(v-y)*k/n,c)

    def box(self,c,x,y,w,h):
        for j in range(y,y+h):
            if 0<=j<88:
                start,end=max(x,0),min(x+w,128)
                if end>start: self.rows[j][start:end]=bytes([c])*(end-start)

    def poly(self,c,*pts):
        for y in range(min(y for x,y in pts),max(y for x,y in pts)+1):
            cuts=[]
            for (x,a),(u,b) in zip(pts,pts[1:]+pts[:1]):
                if min(a,b)<=y<max(a,b): cuts.append(x+(y-a)*(u-x)/(b-a))
            cuts.sort()
            for lo,hi in zip(cuts[::2],cuts[1::2]):
                self.box(c,ceil(lo),y,int(hi)-ceil(lo)+1,1)
        self.line(c,*pts,pts[0])

    def oval(self,c,x,y,w,h):
        for dy in range(-h,h+1):
            dx=round(w*sqrt(max(0,1-(dy/h)**2)))
            self.box(c,x-dx,y+dy,2*dx+1,1)

    def ring(self,c,x,y,w,h):
        pts=[(round(x+w*cos(tau*i/96)),round(y+h*sin(tau*i/96))) for i in range(97)]
        self.line(c,*pts)

    def wheel(self,c,x,y,r,n):
        self.ring(c,x,y,r,r)
        self.ring(c,x,y,r-2,r-2)
        for i in range(n):
            self.line(c,(x,y),(round(x+(r-2)*cos(i*tau/n)),round(y+(r-2)*sin(i*tau/n))))
        self.oval(6,x,y,2,2)


